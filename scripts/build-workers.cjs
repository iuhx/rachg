// Regenerate both Dashboard editor artifacts from their actual Worker sources.
// Uses the bundler shipped with the repository's pinned Wrangler installation.
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
execFileSync(process.execPath, [require.resolve('typescript/bin/tsc'), '-p', path.join(root, 'packages/shared/tsconfig.json')], { stdio: 'inherit' });
const wranglerPackage = fs.realpathSync(path.join(root, 'workers/file-service/node_modules/wrangler/package.json'));
const { build } = createRequire(wranglerPackage)('esbuild');
const targets = [
  ['file-service', 'cloudflare-editor-bundle/index.js'],
  ['mail-ingest', 'cloudflare-editor.js'],
];
(async () => {
  for (const [name, output] of targets) {
    await build({
      absWorkingDir: root,
      entryPoints: [`workers/${name}/src/index.ts`],
      outfile: `workers/${name}/${output}`,
      bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
      banner: { js: '// Generated by scripts/build-workers.cjs. Edit the TypeScript source, not this file.' },
    });
    console.log(`Built ${name} editor artifact`);
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
